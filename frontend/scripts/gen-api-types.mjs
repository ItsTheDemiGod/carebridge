// Generates src/api/openapi.generated.ts (request/body types + the list of endpoints) from ../docs/openapi.json. No dependencies.
// Run: node scripts/gen-api-types.mjs   (a vitest contract test fails when the committed file differs from this output)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
export const SPEC = `${ROOT}../docs/openapi.json`
export const OUT = `${ROOT}src/api/openapi.generated.ts`

function ts(s, indent = '') {
  if (s.$ref) return s.$ref.split('/').pop()
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ')
  if (s.const !== undefined) return JSON.stringify(s.const)
  if (s.anyOf) return s.anyOf.map((x) => ts(x, indent)).join(' | ')
  switch (s.type) {
    case 'string': return 'string'
    case 'integer': case 'number': return 'number'
    case 'boolean': return 'boolean'
    case 'null': return 'null'
    case 'array': return `(${ts(s.items ?? {}, indent)})[]`
    case 'object': {
      const props = s.properties ?? {}
      const keys = Object.keys(props)
      if (!keys.length) return s.additionalProperties && typeof s.additionalProperties === 'object' ? `Record<string, ${ts(s.additionalProperties, indent)}>` : 'Record<string, unknown>'
      const req = new Set(s.required ?? [])
      return `{\n${keys.map((k) => `${indent}  ${k}${req.has(k) ? '' : '?'}: ${ts(props[k], indent + '  ')}`).join('\n')}\n${indent}}`
    }
    default: return 'unknown'
  }
}

export function generate(spec) {
  const out = ['// GENERATED by scripts/gen-api-types.mjs from docs/openapi.json. Do not edit.', '// Response bodies are untyped in openapi.json (the backend returns plain dicts); they are typed by hand in types.ts.', '']
  for (const [name, schema] of Object.entries(spec.components.schemas)) {
    if (name === 'HTTPValidationError' || name === 'ValidationError') continue
    if (schema.enum) {
      const c = name.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase() + 'S'
      out.push(`export const ${c} = ${JSON.stringify(schema.enum)} as const`, `export type ${name} = (typeof ${c})[number]`)
    } else out.push(`export type ${name} = ${ts(schema)}`)
  }
  const eps = []
  for (const [path, m] of Object.entries(spec.paths)) for (const method of Object.keys(m)) eps.push(`${method.toUpperCase()} ${path}`)
  out.push('', `export const ENDPOINTS = ${JSON.stringify(eps.sort(), null, 2)} as const`, '')
  return out.join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, generate(JSON.parse(readFileSync(SPEC, 'utf8'))))
  console.log('wrote', OUT)
}
