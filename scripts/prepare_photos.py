"""Prepares site photographs: reads frontend/public/photos/raw/<name>.jpg (gitignored originals), applies the optional crop
from assets/photo_sources.json, strips metadata, writes <name>-<w>.webp and .jpg (up to 800, 1400 and 2000 px wide, never
upscaled, each file kept near 250 KB or less) to frontend/public/photos/, then writes frontend/src/photos.manifest.json and
the table in assets/ATTRIBUTION.md from assets/photo_sources.json.
python scripts/prepare_photos.py        (Pillow only)"""
import io
import json
from pathlib import Path

from PIL import Image, ImageOps

REPO = Path(__file__).resolve().parents[1]
RAW = REPO / "frontend" / "public" / "photos" / "raw"
OUT = RAW.parent
MANIFEST = REPO / "frontend" / "src" / "photos.manifest.json"
SOURCES = REPO / "assets" / "photo_sources.json"
ATTR = REPO / "assets" / "ATTRIBUTION.md"
WIDTHS = (800, 1400, 2000)
LIMIT = 250 * 1024


def encode(im: Image.Image, fmt: str) -> bytes:
    q = 78
    while True:
        buf = io.BytesIO()
        if fmt == "webp":
            im.save(buf, "WEBP", quality=q, method=6)
        else:
            im.save(buf, "JPEG", quality=q, optimize=True, progressive=True)
        if buf.tell() <= LIMIT or q <= 40:
            return buf.getvalue()
        q -= 6


def main() -> None:
    sources = json.loads(SOURCES.read_text(encoding="utf-8")) if SOURCES.exists() else {}
    manifest = {}
    for f in sorted(RAW.glob("*.jpg")) + sorted(RAW.glob("*.jpeg")) + sorted(RAW.glob("*.png")):
        name = f.stem
        im = ImageOps.exif_transpose(Image.open(f)).convert("RGB")  # new image object: no EXIF or other metadata is carried over
        l, t, r, b = sources.get(name, {}).get("crop", [0, 0, 1, 1])
        W, H = im.size
        im = im.crop((int(l * W), int(t * H), int(r * W), int(b * H)))
        widths = [w for w in WIDTHS if w <= im.width] or [im.width]
        for w in widths:
            small = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
            for ext, fmt in (("webp", "webp"), ("jpg", "jpeg")):
                data = encode(small, fmt)
                (OUT / f"{name}-{w}.{ext}").write_bytes(data)
        manifest[name] = {"width": widths[-1], "height": round(im.height * widths[-1] / im.width), "widths": widths}
        if name in sources:
            manifest[name]["credit"] = f"{sources[name]['photographer']}, {sources[name]['license']}"
            manifest[name]["source"] = sources[name]["source_url"]  # shown as the credit link in the footer (Phase 6c)
        if name not in sources:
            print(f"warning: {name} has no entry in assets/photo_sources.json (add source, photographer, licence)")
        print(f"{name}: {widths} {max((OUT / f'{name}-{widths[-1]}.{e}').stat().st_size for e in ('webp', 'jpg')) // 1024} KB at the largest size")
    MANIFEST.write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8", newline="\n")
    rows = ["# Asset attribution", "", "Generated by `scripts/prepare_photos.py` from `assets/photo_sources.json`. Photographs are self-hosted; originals are not committed.", "",
            "| file | source URL | photographer | licence | date fetched | notes |", "|------|------------|--------------|---------|--------------|-------|"]
    for name in sorted(manifest):
        s = sources.get(name, {})
        rows.append(f"| {name} | {s.get('source_url', '?')} | {s.get('photographer', '?')} | {s.get('license', '?')} | {s.get('date_fetched', '?')} | {s.get('note', '')} |")
    ATTR.write_text("\n".join(rows) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
